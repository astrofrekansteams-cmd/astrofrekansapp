def test_solar_return_puts_the_sun_on_its_natal_degree(chart):
    case = FIXTURES["solar_returns"][0]
    engine = ReturnEngine()
    moment = engine.solar_return_moment(chart, case["year"])
    assert moment is not None

    # Self-verifying: whatever the instant, the Sun must be there.
    from app.services.astrology.sampling import EphemerisSampler

    longitude = EphemerisSampler().value_at(Planet.SUN, moment)
    assert separation(longitude, chart.sun.longitude) < 0.01

    expected = datetime.fromisoformat(case["expected_exact_at"])
    assert abs((moment - expected).total_seconds()) <= case["tolerance_minutes"] * 60


def test_solar_return_chart_is_cast_for_the_return(chart):
    engine = ReturnEngine()
    return_chart = engine.solar_return_chart(chart, 2026)
    assert return_chart is not None
    assert return_chart.kind.value == "solar_return"
    assert return_chart.birth_data is None
    assert len(return_chart.houses) == 12
    assert return_chart.subject.moment_utc.year == 2026


def test_lunar_return_repeats_monthly(chart):
    engine = ReturnEngine()
    first = engine.lunar_return_moment(chart, after=datetime(2026, 1, 1, tzinfo=UTC))
    assert first is not None
    second = engine.lunar_return_moment(chart, after=first + timedelta(days=1))
    assert second is not None
    gap = (second - first).total_seconds() / 86400
    assert 26.0 < gap < 29.0  # sidereal month is 27.32 days
