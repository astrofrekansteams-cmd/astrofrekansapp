def test_published_retrograde_windows(calendar):
    start = datetime(2026, 1, 1, tzinfo=UTC)
    end = datetime(2026, 12, 31, 23, 59, tzinfo=UTC)
    periods = calendar.retrograde_periods(start, end)

    for case in FIXTURES["retrograde_periods_2026"]:
        planet = Planet(case["planet"])
        expected_start = date.fromisoformat(case["station_retrograde"])
        match = next(
            (
                period
                for period in periods
                if period.planet is planet
                and abs((period.start_at.date() - expected_start).days)
                <= case["tolerance_days"]
            ),
            None,
        )
        assert match is not None, f"missing retrograde window {case['id']}"
        assert (
            abs(
                (
                    match.end_at.date() - date.fromisoformat(case["station_direct"])
                ).days
            )
            <= case["tolerance_days"]
        )


def test_stations_are_where_speed_changes_sign(calendar):
    start = datetime(2026, 1, 1, tzinfo=UTC)
    events = calendar.stations(start, start + timedelta(days=200))
    assert events

    for event in events:
        before = calendar.sampler.speeds_at(
            event.planet, [event.exact_at - timedelta(days=2)]
        )[0]
        after = calendar.sampler.speeds_at(
            event.planet, [event.exact_at + timedelta(days=2)]
        )[0]
        assert before * after < 0
        if event.type is CosmicEventType.STATION_RETROGRADE:
            assert after < 0
        else:
            assert after > 0


