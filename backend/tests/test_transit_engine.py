# --------------------------------------------------------- exact timing


def test_exact_times_are_real_perfections(week_scan, transits):
    """At every reported exact instant the aspect really is exact."""
    checked = 0
    for event in week_scan.events:
        target = event.metadata["target_longitude"]
        for item in event.passes:
            longitude = transits.sampler.value_at(
                event.transiting_body, item.exact_at
            )
            orb = abs(separation(longitude, target) - event.aspect_type.angle)
            assert orb < 0.02, f"{event.id} pass {item.pass_number} orb {orb}"
            checked += 1
    assert checked > 0


def test_passes_are_ordered_and_numbered(week_scan):
    for event in week_scan.events:
        numbers = [item.pass_number for item in event.passes]
        assert numbers == list(range(1, len(numbers) + 1))
        moments = [item.exact_at for item in event.passes]
        assert moments == sorted(moments)


def test_window_contains_every_pass(week_scan):
    for event in week_scan.events:
        for item in event.passes:
            assert event.start_at <= item.exact_at <= event.end_at


def test_orb_at_window_edges_is_the_limit(week_scan, transits):
    """The window is where the orb crosses its limit, not a guess."""
    for event in week_scan.events:
        if event.window_clipped:
            continue
        target = event.metadata["target_longitude"]
        for edge in (event.start_at, event.end_at):
            longitude = transits.sampler.value_at(event.transiting_body, edge)
            orb = abs(separation(longitude, target) - event.aspect_type.angle)
            assert orb == pytest.approx(event.maximum_orb, abs=0.1)


def test_applying_and_separating_follow_the_exact_time(week_scan):
    for event in week_scan.events:
        if event.exact_at is None:
            continue
        if event.applying:
            assert event.exact_at >= week_scan.reference
        else:
            assert event.exact_at <= week_scan.reference


def test_status_matches_the_reference_instant(week_scan):
    for event in week_scan.events:
        if event.start_at > week_scan.reference:
            assert event.status is TransitStatus.APPROACHING
        elif event.exact_at and abs(
            (week_scan.reference - event.exact_at).total_seconds()
        ) <= 12 * 3600:
            assert event.status is TransitStatus.EXACT


def test_strength_is_bounded_and_deterministic(chart, transits, week_scan):
    for event in week_scan.events:
        assert 0 <= event.strength <= 100

