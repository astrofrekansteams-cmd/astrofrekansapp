# ------------------------------------------------------ retrograde passes


def test_retrograde_transit_perfects_more_than_once(chart, transits):
    """A slow planet that stations inside its orb perfects several times.

    Over a year at least one outer-planet transit must show multiple passes
    with a retrograde one among them - that is the whole reason ``passes``
    exists.
    """
    start = datetime(2026, 1, 1, tzinfo=UTC)
    scan = transits.scan(
        chart,
        start=start,
        end=start + timedelta(days=365),
        reference=start,
        include_moon=False,
        chart_fingerprint="multi",
    )

    multi = [event for event in scan.events if event.is_multi_pass]
    assert multi, "no multi-pass transit found in a whole year"

    retrograde_passes = [
        item
        for event in multi
        for item in event.passes
        if item.direction is PassDirection.RETROGRADE
    ]
    assert retrograde_passes

    for event in multi:
        # A three-pass transit goes direct, retrograde, direct.
        directions = [item.direction for item in event.passes]
        assert PassDirection.RETROGRADE in directions or len(directions) == 2
        assert event.strength >= 0


def test_pass_direction_matches_the_speed_sign(week_scan):
    for event in week_scan.events:
        for item in event.passes:
            if item.direction is PassDirection.RETROGRADE:
                assert item.speed < 0
            else:
                assert item.speed >= 0


# ----------------------------------------------------------- house ingress


def test_house_ingress_is_a_real_cusp_crossing(chart, transits, week_scan):
    assert week_scan.ingresses
    cusps = {house.number: house.cusp_longitude for house in chart.houses}

    for ingress in week_scan.ingresses:
        longitude = transits.sampler.value_at(ingress.planet, ingress.entered_at)
        cusp = cusps[ingress.to_house if not ingress.retrograde else ingress.from_house]
        assert separation(longitude, cusp) < 0.05
        assert 1 <= ingress.from_house <= 12
        assert 1 <= ingress.to_house <= 12
        assert ingress.from_house != ingress.to_house


def test_retrograde_re_entry_is_marked(chart, transits):
    """A retrograding planet leaves a house and comes back; the second entry
    is flagged rather than reported as a fresh ingress."""
    start = datetime(2026, 1, 1, tzinfo=UTC)
    scan = transits.scan(
        chart,
        start=start,
        end=start + timedelta(days=365),
        reference=start,
        include_moon=False,
        chart_fingerprint="ingress",
    )
    assert scan.ingresses
    re_entries = [item for item in scan.ingresses if item.re_entry]
    assert re_entries, "expected at least one house re-entry in a year"
    assert any(item.retrograde for item in scan.ingresses)


def test_ingress_exit_follows_entry(week_scan):
    for ingress in week_scan.ingresses:
        if ingress.estimated_exit_at is not None:
            assert ingress.estimated_exit_at > ingress.entered_at


# ------------------------------------------------------------- calendar


def test_moon_phases_are_quarter_turns(calendar):
    start = datetime(2026, 4, 1, tzinfo=UTC)
    events = calendar.events(
        start,
        start + timedelta(days=40),
        include_stations=False,
        include_ingresses=False,
        include_aspects=False,
        include_eclipses=False,
    )
    phases = [event for event in events if event.type.is_moon_phase]
    assert len(phases) >= 4

    expected = {
        CosmicEventType.NEW_MOON: 0.0,
        CosmicEventType.FIRST_QUARTER: 90.0,
        CosmicEventType.FULL_MOON: 180.0,
        CosmicEventType.LAST_QUARTER: 270.0,
    }
    for event in phases:
        sun = calendar.sampler.value_at(Planet.SUN, event.exact_at)
        moon = calendar.sampler.value_at(Planet.MOON, event.exact_at)
        elongation = (moon - sun) % 360.0
        assert separation(elongation, expected[event.type]) < 0.05


def test_published_eclipses_are_found_and_nothing_is_invented(calendar):
    """All four 2026 eclipses, on the published dates, and no false positives."""
    start = datetime(2026, 1, 1, tzinfo=UTC)
    end = datetime(2026, 12, 31, 23, 59, tzinfo=UTC)
    events = calendar.events(
        start,
        end,
        include_stations=False,
        include_ingresses=False,
        include_aspects=False,
    )
    eclipses = [event for event in events if event.type.is_eclipse]
    expected = FIXTURES["eclipses_2026"]

    assert len(eclipses) == len(expected), (
        "eclipse count differs from the NASA catalogue: "
        f"{[event.exact_at.date().isoformat() for event in eclipses]}"
    )

    for case in expected:
        match = next(
            (
                event
                for event in eclipses
                if event.exact_at.date().isoformat() == case["date"]
            ),
            None,
        )
        assert match is not None, f"missing eclipse {case['id']}"
        assert match.type.value == case["type"]

        if case["type"] == "lunar_eclipse":
            assert match.eclipse_subtype is not None
            assert match.eclipse_subtype.value == case["engine_subtype_expected"]
        else:
            # Solar subtype needs Besselian elements: null, never guessed.
            assert match.eclipse_subtype is None


